"""How the optimised files go back into the Next.js fixture (called by tests/run_fixture.py on a copy of the project).

next/font/local cannot give one file its own `unicode-range`, so the `localFont()` calls are replaced by plain @font-face
rules (the generated ones). Everything else next/font did is kept: the family names, the `--font-geist-*` CSS
variables, the metric-matched "<family> Fallback" faces (copied byte for byte from the baseline build's CSS), and the
preloads (core files only, and only because the baseline preloaded them: --preload auto).
"""
import re
import shutil
from pathlib import Path


def baseline_css(dist: Path) -> str:
    return "\n".join(p.read_text() for p in sorted((dist / "_next/static").rglob("*.css")))


def wire(proj: Path, opt: Path, ctx: dict):
    manifest = ctx["manifest"]
    base = baseline_css(ctx["before_dist"])
    fallbacks = re.findall(r"@font-face\{font-family:[^;]+? Fallback;[^}]*\}", base)
    variables = re.findall(r"\.\w+_variable\{(--font-[^}]+)\}", base)
    assert fallbacks and variables, "could not find next/font's fallback faces / variables in the baseline CSS"

    pub = proj / "public/fonts/optimized"
    pub.mkdir(parents=True)
    for p in opt.glob("*.woff2"):
        shutil.copy(p, pub / p.name)
    shutil.rmtree(proj / "app/fonts")
    (proj / "app/fonts.js").unlink()

    css = (opt / "fonts.generated.css").read_text()
    (proj / "app/optimized-fonts.css").write_text(
        "/* generated by optimize_fonts.py (the @font-face rules) + copied from the baseline build (fallback faces, variables) */\n"
        + css + "\n" + "\n".join(fallbacks) + "\n:root{" + ";".join(variables) + "}\n")

    layout = proj / "app/layout.js"
    s = layout.read_text()
    s = s.replace("import { geistSans, geistMono } from './fonts';\n", "import ReactDOM from 'react-dom';\n")
    s = s.replace("import './globals.css';", "import './optimized-fonts.css';\nimport './globals.css';")
    s = s.replace("export default function RootLayout({ children }) {\n",
                  "export default function RootLayout({ children }) {\n"
                  + "".join(f"  ReactDOM.preload('/fonts/optimized/{Path(u).name}', {{ as: 'font', type: 'font/woff2', crossOrigin: 'anonymous' }});\n"
                          for u in sorted(set(manifest["preload_replacements"].values()))))
    s = s.replace(' className={`${geistSans.variable} ${geistMono.variable}`}', "")
    layout.write_text(s)
